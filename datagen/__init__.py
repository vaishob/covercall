class DataGateError(ValueError):
    """Raised when a staff record violates CO-AGE-SCOPE (age < 16)."""


def validate_and_load_staff(staff_list: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Enforce CO-AGE-SCOPE and synthetic flag at data load time (§1.2, §6.2)."""
    rules = load_rules()
    age_rules = [r for r in rules if r["id"] == "CO-AGE-SCOPE"]
    validated: list[dict[str, Any]] = []
    for rec in staff_list:
        if not rec.get("synthetic"):
            raise ValueError(f"Staff record {rec.get('staff_id')} is missing synthetic: true")
        if "part4_covered" in rec:
            raise ValueError(
                f"Staff record {rec.get('staff_id')} stores part4_covered by hand; must be computed by SG-EA4-COVERAGE"
            )
        age = int(rec.get("age", 0))
        res = validate_assignment({"employee": rec, "shift": {}, "ledger": {}}, {}, age_rules)
        if age < 16 or any(r.status == "violation" for r in res):
            raise DataGateError(
                f"CO-AGE-SCOPE violation: staff {rec.get('staff_id')} has age {age} (< 16)"
            )
        validated.append(rec)
    return validated


